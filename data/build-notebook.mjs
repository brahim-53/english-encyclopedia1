import { readFile, writeFile } from 'node:fs/promises';
import { fromEnglishCatalog as english } from '../app/locale/index.js';

const source = new URL('../public/notebook/index.html', import.meta.url);
const output = new URL('../sections/fundamentals/data/notebook-index.js', import.meta.url);

// Index the real notebook's literals without running its inline script or
// duplicating its teaching content by hand. Links open the original cards.
export function indexNotebook(html) {
  const literal = (name) => {
    const match = html.match(new RegExp(`const ${name}=([\\s\\S]*?);\\r?\\n(?=const )`));
    if (!match) throw new Error(`Notebook data missing: ${name}`);
    return JSON.parse(match[1]);
  };
  const entries = [];
  const row = (text) => text.replace(/[\[\]]/g, '').replace(/~(\S+)/g, ' /$1/');
  for (const [, , cards] of literal('S')) {
    for (const item of cards) {
      const [symbol, label, tip, ...words] = item.split(';');
      entries.push([`s-${entries.length + 1}`, `/${symbol}/ ${symbol}`, label, [tip, ...words.map(row)].join(' '),
        english(label), [english(tip), ...words.map(row)].join(' '), `/${symbol}/ ${symbol}`]);
    }
  }
  for (const [, label, cards] of literal('P')) {
    for (const item of cards) {
      const [title, tip, ...words] = item.split(';');
      entries.push(['letters', title, label.slice(1), [tip, ...words.map(row)].join(' '),
        english(label).replace(/^#/, ''), [english(tip), ...words.map(row)].join(' '), english(title)]);
    }
  }
  for (const [title, item] of literal('C')) {
    const [tip, ...words] = item.split(';');
    entries.push(['cmp', title, 'مقارنات الأصوات', [tip, ...words.map(row)].join(' '),
      'Sound comparisons', [english(tip), ...words.map(row)].join(' '), title]);
  }
  return entries;
}

export async function buildNotebookIndex() {
  const entries = indexNotebook(await readFile(source, 'utf8'));
  await writeFile(output, `// Generated by npm run build from the original notebook; do not edit.\nexport const notebookIndex = ${JSON.stringify(entries, null, 2)};\n`);
}
