"""Build supplementary dictionary datasets for the Word Analyzer & smart search.

Inputs:
  - CEFR Arabic-meanings list (exported from the reviewed source project data):
      {w, ar, ipa, level, pos, src}  — 9,871 entries, all with Arabic meanings.
  - CMU Pronouncing Dictionary (data/dict/cmu_original.dict) — authoritative GA
    pronunciation used to compute the IPA shown for ending-pattern words, so all
    IPA on this platform comes from the same source (CMUdict), never re-typed.

Outputs (classic <script> files so they load from file:// without fetch):
  - public/dict/cefr-ar.js   -> window.__ERP_CEFR = { word: [arabicMeaning, cefrLevel], ... }
    Loaded on demand by the Word Analyzer / smart search to show the Arabic
    meaning of a looked-up common word. Pronunciation is NOT taken from this
    file — it always comes from CMUdict.
  - public/dict/endings.js   -> window.__ERP_ENDINGS = { pattern: [{w, ipa, ar, lv}, ...] }
    Up to 12 common words per spelling-ending pattern (words that exist in the
    CEFR list so they are frequent and carry an Arabic meaning), with IPA
    computed from CMUdict. Used by the "-tion"-style pattern search.

Usage: python3 data/build-cefr.py  (expects /tmp/cefr.json — see README)
"""
import json, os, re, collections

HERE = os.path.dirname(__file__)
CEFR_JSON = os.environ.get("CEFR_JSON", "/tmp/cefr.json")
CMU = os.path.join(HERE, "dict", "cmu_original.dict")
OUT = os.path.join(HERE, "..", "public", "dict")

# ARPAbet -> GA IPA (mirrors sections/fundamentals/tools/arpabet.js)
A2I = {
    "AA": "ɑ", "AE": "æ", "AH": "ʌ", "AO": "ɔ", "AW": "aʊ", "AY": "aɪ",
    "B": "b", "CH": "tʃ", "D": "d", "DH": "ð", "EH": "ɛ", "EY": "eɪ", "F": "f",
    "G": "g", "HH": "h", "IH": "ɪ", "IY": "iː", "JH": "dʒ", "K": "k", "L": "l",
    "M": "m", "N": "n", "NG": "ŋ", "OW": "oʊ", "OY": "ɔɪ", "P": "p", "R": "r",
    "S": "s", "SH": "ʃ", "T": "t", "TH": "θ", "UH": "ʊ", "UW": "uː", "V": "v",
    "W": "w", "Y": "j", "Z": "z", "ZH": "ʒ",
}

def phone_ipa(base, st):
    if base == "AH": return "ə" if st == "0" else "ʌ"
    if base == "ER": return "ɚ" if st == "0" else "ɝ"
    if base == "IY": return "i" if st == "0" else "iː"
    if base == "UW": return "u" if st == "0" else "uː"
    return A2I.get(base)

def arpabet_to_ipa(phones):
    out, cluster_start = [], 0
    for ph in phones:
        m = re.match(r"^([A-Z]+)([0-9])?$", ph)
        if not m:
            continue
        base, st = m.group(1), m.group(2)
        ipa = phone_ipa(base, st)
        if ipa is None:
            continue
        if base[0] in "AEIOU":
            if st in ("1", "2"):
                out.insert(cluster_start, "ˈ" if st == "1" else "ˌ")
                cluster_start += 1
            out.append(ipa)
            cluster_start = len(out)
        else:
            out.append(ipa)
    return "".join(out)

# ---- load CMUdict (first pronunciation wins) ----
cmu = {}
with open(CMU, encoding="utf-8") as f:
    for line in f:
        line = line.split("#")[0].strip()
        if not line:
            continue
        w, *ph = line.split()
        w = re.sub(r"\(\d+\)$", "", w).lower()
        if w not in cmu:
            cmu[w] = ph

# ---- load CEFR list ----
cefr = json.load(open(CEFR_JSON, encoding="utf-8"))
by_word = {}
for x in cefr:
    w = str(x.get("w", "")).strip().lower()
    if w and w not in by_word:
        by_word[w] = x

# ---- 1) cefr-ar.js ----
ar_map = {w: [x.get("ar", ""), x.get("level", "")] for w, x in by_word.items() if x.get("ar")}
os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "cefr-ar.js"), "w", encoding="utf-8") as f:
    f.write("// Arabic meanings + CEFR levels for common English words (9,871 entries).\n")
    f.write("// Generated by data/build-cefr.py — do not edit by hand.\n")
    f.write("// Pronunciations are NOT stored here; they always come from CMUdict.\n")
    f.write('window.__ERP_CEFR = ')
    f.write(json.dumps(ar_map, ensure_ascii=False, separators=(",", ":")))
    f.write(";\n")

# ---- 2) endings.js ----
# pattern -> topic id (verified against sections/fundamentals/data/endings.js)
PATTERNS = {
    "tion": "suffix-tion", "sion": "suffix-sion", "cian": "suffix-cian",
    "cial": "suffix-cial-tial", "tial": "suffix-cial-tial", "ture": "suffix-ture",
    "ous": "suffix-ous", "ious": "suffix-ous", "ity": "suffix-ity",
    "ive": "suffix-ive", "ize": "suffix-ize", "ise": "suffix-ize",
    "ment": "suffix-ment", "ness": "suffix-ness", "able": "suffix-able",
    "ible": "suffix-able", "ly": "suffix-ly", "al": "suffix-al", "ic": "suffix-ic",
    "ed": "suffix-ed", "es": "suffix-es", "s": "suffix-s", "ion": "suffix-ion-related",
}
LV = {"A1": 0, "A2": 1, "B1": 2, "B2": 3, "C1": 4, "": 5}
endings = {}
for pat in PATTERNS:
    hits = []
    for w, x in by_word.items():
        if w.endswith(pat) and len(w) >= len(pat) + 2 and w in cmu:
            hits.append((LV.get(x.get("level", ""), 5), w, x))
    hits.sort()
    seen, rows = set(), []
    for _, w, x in hits:
        if w in seen:
            continue
        seen.add(w)
        rows.append({
            "w": w,
            "ipa": arpabet_to_ipa(cmu[w]),
            "ar": x.get("ar", ""),
            "lv": x.get("level", ""),
        })
        if len(rows) >= 12:
            break
    if rows:
        endings[pat] = rows

with open(os.path.join(OUT, "endings.js"), "w", encoding="utf-8") as f:
    f.write("// Common words per spelling-ending pattern, for the \"-tion\" pattern search.\n")
    f.write("// Generated by data/build-cefr.py from the CEFR common-words list; IPA computed\n")
    f.write("// from CMUdict (GA). Do not edit by hand.\n")
    f.write('window.__ERP_ENDINGS = ')
    f.write(json.dumps(endings, ensure_ascii=False, separators=(",", ":")))
    f.write(";\n")

total = sum(len(v) for v in endings.values())
print(f"cefr-ar.js: {len(ar_map)} entries")
print(f"endings.js: {len(endings)} patterns, {total} words")
missing = [p for p in PATTERNS if p not in endings]
if missing:
    print("patterns with no words:", missing)
